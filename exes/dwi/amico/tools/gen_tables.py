"""Write src/tables.rs from AMICO 1.5.4: the data its NODDI kernels use that does not depend on
the acquisition. Run with AMICO 1.5.4 (dmri-amico==1.5.4, dipy 1.7) installed:

    python -I tools/gen_tables.py > src/tables.rs

- GRAD_Z: the z component of AMICO's 500 high-resolution directions (amico.lut.grad), after
  amico.scheme.Scheme makes the y component non-negative. The atoms are symmetric about z, so
  they depend on this component only.
- FIT_M0: the m = 0 rows (l = 0, 2, ..., 12) of AUX['fit'], the least-squares fit of dipy's
  real symmetric SH basis (lmax 12) on those directions (amico.lut.precompute_rotation_matrices).
- LUT_DIR0: the first direction of the 32761-direction lookup table. AMICO normalises each
  atom for the LASSO by its norm at this direction (models.NODDI.resample).
"""

import sys

import amico.lut
import numpy as np
from dipy.core.geometry import cart2sphere
from dipy.reconst.shm import real_sym_sh_basis

LMAX = 12

# precompute_rotation_matrices fits the SH on amico.lut.grad as it is; Scheme flips it later.
raw = np.array(amico.lut.grad, dtype=np.float64)
_, theta, phi = cart2sphere(raw[:, 0], raw[:, 1], raw[:, 2])
basis, _, _ = real_sym_sh_basis(LMAX, theta, phi)
fit = np.dot(np.linalg.pinv(np.dot(basis.T, basis)), basis.T)
m0 = [int((l * l + l + 2) / 2 - 1) for l in range(0, LMAX + 1, 2)]
dir0 = amico.lut.load_directions(32761)[0]
grad = raw.copy()
flip = grad[:, 1] < 0
grad[flip] = -grad[flip]


def row(values):
    return ", ".join(repr(float(v)) for v in values)


out = sys.stdout
out.write(
    "// @generated by tools/gen_tables.py from AMICO 1.5.4 (dmri-amico, BSD-3-Clause). Do not edit.\n\n"
)
out.write(f"pub const N_HR: usize = {len(grad)};\n")
out.write(f"pub const N_L: usize = {len(m0)};\n\n")
out.write(f"pub static GRAD_Z: [f64; N_HR] = [{row(grad[:, 2])}];\n\n")
out.write("pub static FIT_M0: [[f64; N_HR]; N_L] = [\n")
for i in m0:
    out.write(f"    [{row(fit[i])}],\n")
out.write("];\n\n")
out.write(f"pub const LUT_DIR0: [f64; 3] = [{row(dir0)}];\n")
